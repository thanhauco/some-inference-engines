"""Export the numbers shown in the videos from the repo's own simulations.

    python videos/export_data.py        # rewrites videos/src/data.js

Every figure that appears on screen comes from here, so the videos can't drift from the
code: change a simulation, re-export, re-render.
"""

from __future__ import annotations

import json
from pathlib import Path

from inference_engines.concepts import (
    batching,
    constrained,
    fusion,
    kv_cache,
    memory,
    offload,
    prefill_decode,
    prefix_caching,
    quantization,
    radix_cache,
    routing,
    speculative,
)

OUT = Path(__file__).parent / "src" / "data.js"


def collect() -> dict:
    static, continuous = batching.compare()
    lens = [180, 950, 64, 2200, 410, 75, 1300, 512]
    radix = radix_cache.prefill_savings(radix_cache.agent_workload())
    prefix = {(r.cache, r.policy): r for r in prefix_caching.head_to_head(capacity_tokens=3000)}
    target = speculative.ToyLM(seed=1)
    _, spec = speculative.generate([1, 2], 400, target, speculative.DraftLM(target, 0.9), k=4)
    schema = {
        "type": "object",
        "properties": {
            "customer": {"type": "string", "maxLength": 12},
            "priority": {"type": "integer"},
            "category": {"enum": ["billing", "bug", "feature_request"]},
            "escalate": {"type": "boolean"},
        },
    }
    model = constrained.random_char_model(3)
    _, slow = constrained.generate_json(schema, model, jump_forward=False, seed=3)
    _, fast = constrained.generate_json(schema, model, jump_forward=True, seed=3)
    quant = {r["format"]: r for r in quantization.compare_formats()}
    spec8b = memory.MODELS["llama-3.1-8b"]
    mono, chunked, disagg = prefill_decode.compare()
    routes = {r.policy: r for r in routing.compare_policies()}
    return {
        "batching": {
            "static_tok_s": round(static.throughput_tok_s),
            "continuous_tok_s": round(continuous.throughput_tok_s),
            "static_ttft_ms": round(static.mean_ttft_ms),
            "continuous_ttft_ms": round(continuous.mean_ttft_ms),
            "static_util": round(static.slot_utilization, 3),
            "continuous_util": round(continuous.slot_utilization, 3),
        },
        "paged": {
            "contiguous_util": round(kv_cache.contiguous_utilization(lens, 4096), 3),
            "paged_util": round(kv_cache.paged_utilization(lens, 16), 3),
            "kv_kib_per_token": memory.kv_bytes_per_token(spec8b) / 1024,
        },
        "radix": radix,
        "prefix": {
            "fcfs_hit": prefix[("radix (SGLang)", "fcfs")].hit_rate,
            "lpm_hit": prefix[("radix (SGLang)", "lpm")].hit_rate,
            "vllm_fcfs_hit": prefix[("block-hash (vLLM)", "fcfs")].hit_rate,
        },
        "speculative": {
            "acceptance": round(spec.acceptance_rate, 2),
            "tokens_per_pass": round(spec.tokens_per_target_call, 2),
        },
        "constrained": {"calls_plain": slow.model_calls, "calls_jump": fast.model_calls},
        "fusion": fusion.fusion_report(),
        "quantization": {
            "fp8_x": quant["FP8 E4M3 per-tensor"]["compression"],
            "int4_x": quant["INT4 group-128 (W4A16)"]["compression"],
            "bf16_gib": round(memory.weight_bytes(spec8b, "bf16") / memory.GiB, 1),
            "fp8_gib": round(memory.weight_bytes(spec8b, "fp8") / memory.GiB, 1),
            "int4_gib": round(memory.weight_bytes(spec8b, "int4") / memory.GiB, 1),
        },
        "ollama": {
            "q4_gib": round(memory.weight_bytes(spec8b, "q4_K_M") / memory.GiB, 1),
            "q4_gb": round(memory.weight_bytes(spec8b, "q4_K_M") / 1e9, 1),
            "offload": [
                {"vram": p.vram_gib, "gpu_layers": p.gpu_layers, "tok_s": round(p.tokens_per_s, 1)}
                for p in offload.offload_curve(vram_options=(0, 4, 6, 8))
            ],
            "cold_start_s": round(offload.cold_start_s("llama-3.1-8b"), 1),
        },
        "interference": {
            "mono_itl_max": round(mono.itl_max_ms),
            "chunked_itl_max": round(chunked.itl_max_ms),
            "disagg_itl_max": round(disagg.itl_max_ms),
            "itl_p50": round(mono.itl_p50_ms, 1),
        },
        "routing": {k: round(v.hit_rate, 3) for k, v in routes.items()},
    }


def main() -> None:
    data = collect()
    OUT.write_text(
        "// Generated by videos/export_data.py from the simulations - do not edit by hand.\n"
        f"window.SIM = {json.dumps(data, indent=2)};\n"
    )
    print(f"wrote {OUT} ({len(data)} sections)")


if __name__ == "__main__":
    main()
